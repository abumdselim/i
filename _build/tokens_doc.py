"""Generate the design-token reference from the single token source.

Called by build.py so the documentation can never drift from the CSS.
Reads _build/tokens.css, writes docs/TOKENS.md and docs/tokens.json.
"""

import json
import pathlib
import re

ROLE = {
    '--bg': 'page surface',
    '--bg-2': 'tinted band, page head, hero, footer',
    '--bg-3': 'inset figure / plate ground',
    '--surface': 'cards, plates, map cells',
    '--ink': 'primary text',
    '--ink-2': 'strong secondary text',
    '--muted': 'body secondary text',
    '--muted-2': 'mono labels and metadata',
    '--line': 'hairline',
    '--line-2': 'strong hairline',
    '--accent': 'brand blue, primary action',
    '--accent-ink': 'blue text on light surfaces',
    '--accent-tint': 'soft brand wash',
    '--ink-surface': 'the dark band',
    '--on-ink': 'text on the dark band',
    '--on-ink-muted': 'secondary text on the dark band',
    '--on-ink-line': 'hairline on the dark band',
    '--head-bg': 'header surface (kept opaque)',
    '--shadow-focus': 'focus ring',
    '--font-sans': 'display and body family',
    '--font-mono': 'labels, metadata, diagram annotation',
    '--shell': 'content max width',
    '--gutter': 'page gutter',
    '--sec': 'section vertical padding',
    '--head-h': 'fixed header height',
    '--r': 'input radius',
}

GROUPS = [
    ('Surfaces', ['--bg', '--bg-2', '--bg-3', '--surface', '--ink-surface']),
    ('Text', ['--ink', '--ink-2', '--muted', '--muted-2', '--on-ink', '--on-ink-muted']),
    ('Lines', ['--line', '--line-2', '--on-ink-line']),
    ('Brand', ['--accent', '--accent-ink', '--accent-tint']),
    ('Chrome', ['--head-bg', '--shadow-focus']),
    ('Layout', ['--shell', '--gutter', '--sec', '--head-h', '--r']),
    ('Type', ['--font-sans', '--font-mono']),
]


def parse(css):
    blocks = re.findall(r'(:root|html\[data-theme="dark"\])\s*\{(.*?)\}', css, re.S)
    out = {}
    for selector, body in blocks:
        theme = 'light' if selector == ':root' else 'dark'
        for name, value in re.findall(r'(--[\w-]+)\s*:\s*([^;]+);', body):
            out.setdefault(name, {})[theme] = value.strip()
    return out


def write_token_docs(tokens_css_path='_build/tokens.css', docs_dir='docs'):
    css = pathlib.Path(tokens_css_path).read_text(encoding='utf-8')
    tokens = parse(css)

    docs = pathlib.Path(docs_dir)
    docs.mkdir(exist_ok=True)
    (docs / 'tokens.json').write_text(
        json.dumps({'source': tokens_css_path, 'tokens': tokens}, indent=2, ensure_ascii=False) + '\n',
        encoding='utf-8'
    )

    def esc(v):
        return v.replace('|', '\\|')

    rows = []
    for title, names in GROUPS:
        rows.append('### %s\n' % title)
        rows.append('| Token | Light | Dark | Role |')
        rows.append('|---|---|---|---|')
        for n in names:
            if n not in tokens:
                continue
            light = tokens[n].get('light', '—')
            dark = tokens[n].get('dark', light)
            if len(light) > 34:
                light = light[:31] + '…'
            if len(dark) > 34:
                dark = dark[:31] + '…'
            rows.append('| `%s` | `%s` | `%s` | %s |' % (n, esc(light), esc(dark), ROLE.get(n, '')))
        rows.append('')

    body = '\n'.join(rows)

    text = f"""# Design tokens

Single source: **`_build/tokens.css`**. It is prepended to the stylesheet at build time, so
every page in the site reads these values. This file and `tokens.json` are generated by
`_build/tokens_doc.py` during the build — do not edit them by hand.

- Machine-readable: [`tokens.json`](tokens.json)
- Consumed by: `_build/build.py` → inlined `<style>` on all 19 pages
- Naming rule: tokens are named by **role**, never by hue (`--accent`, not `--blue`)

## Colour

{body}
Every colour in the site comes from these tokens. Hard-coded hex values outside this file
are a defect. Contrast targets: body text ≥ 4.5:1, large display text ≥ 3:1, UI borders
≥ 3:1 against their surface.

## Typography

| Role | Family | Size | Weight | Tracking | Leading |
|---|---|---|---|---|---|
| Display | `--font-sans` | `clamp(2.7rem, 5.4vw, 4.35rem)` | 600 | `-.025em` | `.96` |
| H2 | `--font-sans` | `clamp(1.95rem, 3.35vw, 2.9rem)` | 600 | `-.024em` | `1.04` |
| H3 | `--font-sans` | `clamp(1.15rem, 1.5vw, 1.375rem)` | 600 | `-.016em` | `1.28` |
| Lead | `--font-sans` | `clamp(1.03rem, 1.15vw, 1.19rem)` | 400 | `-.008em` | `1.58` |
| Body | `--font-sans` | `1rem` | 400 | `-.003em` | `1.68` |
| Small | `--font-sans` | `.875rem` | 400 | `0` | `1.6` |
| Eyebrow / label | `--font-mono` | `.6875rem` / `.625rem` | 400 | `.1em` caps | `1–1.4` |

Weights are limited to 400 (read), 500 (emphasise) and 600 (announce). Fonts are embedded
as base64 WOFF2 — there is no runtime font request.

## Space and layout

| Token | Value | Meaning |
|---|---|---|
| `--shell` | `1320px` | maximum content width |
| `--gutter` | `clamp(20px, 4vw, 56px)` | page gutter |
| `--sec` | `clamp(72px, 8.4vw, 124px)` | section vertical padding |
| `--head-h` | `74px` | fixed header height (drives `body` padding and anchor offset) |
| `--r` | `2px` | input radius; everything else is square |

The spacing scale in use: 4, 8, 10, 12, 14, 16, 18, 20, 22, 24, 28, 32, 40, 48, 64, 72, 96,
124 px. Component padding is fluid (`clamp`) so the same rule works at 360 px and 1440 px.

## Borders, shadow, motion

- Borders: `1px` hairlines only, `--line` or `--line-2`. No other widths.
- Shadows: none. The only `box-shadow` in the system is the focus ring
  (`--shadow-focus`). Depth comes from the surface ladder.
- Radii: `2px` on inputs, `0` everywhere else. The one exception is the clipped corner on
  primary buttons and the CTA block (`clip-path`, 12 px / 44 px).
- Motion: 180–250 ms on hover, 700 ms scroll reveal, 440 ms plate assembly (16 ms stagger).
  All of it is removed under `prefers-reduced-motion`.

## Breakpoints

| Width | What changes |
|---|---|
| 1080px | navigation collapses into the menu button |
| 980px | hero becomes a single column |
| 900px | splits, service layout collapse |
| 860px | product grid, footer columns |
| 680px | capability grid, stack tiles |
| 560px | steps become a vertical timeline |

## Changing the brand colour

Edit `--accent` (light) and `--accent` (dark) in `_build/tokens.css`, then check the two
derived tokens by hand: `--accent-ink` (text on light) and `--accent-tint` (wash). Rebuild;
the contrast of white-on-accent and accent-on-paper must still clear 4.5:1.
"""
    (docs / 'TOKENS.md').write_text(text, encoding='utf-8')
    return len(tokens)
