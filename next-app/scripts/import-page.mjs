#!/usr/bin/env node
/**
 * One-shot importer: legacy page fragment -> TypeScript component.
 *
 * The legacy build emits fully resolved HTML (placeholders expanded, icons
 * inlined, links relative). This turns one page's `<main>` into a server
 * component, applying exactly the renames React needs and nothing else.
 *
 * Deliberate, auditable transforms:
 *   class=           -> className=
 *   stroke-width=... -> strokeWidth=...        (SVG attribute names)
 *   style="a:b"      -> style={css({ a: 'b' })}
 *   href="x.html"    -> href="/x"              (absolute routes)
 *   href="assets/.." -> href="/assets/.."
 *   focusable="..."  -> dropped                (IE-only, untyped)
 *   &amp; &ndash;    -> literal characters
 *
 * Usage: node scripts/import-page.mjs <legacy.html> <out.tsx> <ComponentName>
 */
import fs from 'node:fs';
import path from 'node:path';

const [, , fromArg, toArg, componentName] = process.argv;
if (!fromArg || !toArg || !componentName) {
  console.error('usage: node scripts/import-page.mjs <legacy.html> <out.tsx> <ComponentName>');
  process.exit(1);
}

const appRoot = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const source = fs.readFileSync(path.resolve(process.cwd(), fromArg), 'utf8');

const mainMatch = /<main id="main">([\s\S]*?)<\/main>/.exec(source);
if (!mainMatch) {
  console.error('import-page: no <main id="main"> in ' + fromArg);
  process.exit(1);
}
let body = mainMatch[1];

const ATTR_RENAMES = {
  class: 'className',
  'stroke-width': 'strokeWidth',
  'stroke-linecap': 'strokeLinecap',
  'stroke-linejoin': 'strokeLinejoin',
  'stroke-dasharray': 'strokeDasharray',
  'stroke-dashoffset': 'strokeDashoffset',
  'stroke-miterlimit': 'strokeMiterlimit',
  'stroke-opacity': 'strokeOpacity',
  'fill-rule': 'fillRule',
  'clip-rule': 'clipRule',
  'clip-path': 'clipPath',
  'fill-opacity': 'fillOpacity',
  'stop-color': 'stopColor',
  'text-anchor': 'textAnchor',
  'font-size': 'fontSize',
  'font-weight': 'fontWeight',
  'font-family': 'fontFamily',
  'letter-spacing': 'letterSpacing',
  'dominant-baseline': 'dominantBaseline',
  'paint-order': 'paintOrder',
  'shape-rendering': 'shapeRendering',
  'vector-effect': 'vectorEffect',
  'xmlns:xlink': 'xmlnsXlink',
};

const DROPPED_ATTRS = new Set(['focusable']);

const ENTITIES = {
  '&amp;': '&',
  '&ndash;': '\u2013',
  '&mdash;': '\u2014',
  '&nbsp;': '\u00a0',
  '&copy;': '\u00a9',
  '&hellip;': '\u2026',
  '&rsquo;': '\u2019',
  '&lsquo;': '\u2018',
  '&quot;': '"',
  '&#39;': "'",
};

function decodeEntities(text) {
  return text.replace(/&(?:amp|ndash|mdash|nbsp|copy|hellip|rsquo|lsquo|quot|#39);/g, (m) => ENTITIES[m] ?? m);
}

function camel(key) {
  return key.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
}

function styleObject(style) {
  const decls = style
    .split(';')
    .map((d) => d.trim())
    .filter(Boolean)
    .map((decl) => {
      const at = decl.indexOf(':');
      if (at < 0) throw new Error('unparsed style declaration: ' + decl);
      const key = decl.slice(0, at).trim();
      const value = decl.slice(at + 1).trim();
      return key.startsWith('--') ? `'${key}': '${value}'` : `${camel(key)}: '${value}'`;
    });
  return `css({ ${decls.join(', ')} })`;
}

function rewriteUrl(value) {
  if (/^(?:[a-z]+:|\/|#)/i.test(value)) return value;
  if (value.startsWith('assets/')) return '/' + value;
  if (value === 'index.html') return '/';
  if (value.endsWith('.html')) return '/' + value.slice(0, -5);
  return value;
}

let usedCss = false;

body = body.replace(/<!--[\s\S]*?-->/g, '');

body = body.replace(/<([a-zA-Z][\w-]*)((?:\s+[^\s=>/]+(?:="[^"]*")?)*)(\s*\/?)>/g, (tag, name, attrs, selfClose) => {
  const out = [];
  const attrRe = /([^\s=]+)(?:="([^"]*)")?/g;
  let m;
  while ((m = attrRe.exec(attrs))) {
    const [raw, rawName, rawValue] = m;
    if (!rawName) continue;
    if (DROPPED_ATTRS.has(rawName)) continue;

    let attrName = ATTR_RENAMES[rawName] ?? rawName;
    if (rawValue === undefined) {
      out.push(attrName);
      continue;
    }

    if (rawName === 'style') {
      usedCss = true;
      out.push(`style={${styleObject(decodeEntities(rawValue))}}`);
      continue;
    }
    if (rawName === 'class') attrName = 'className';

    let value = decodeEntities(rawValue);
    if ((attrName === 'href' || attrName === 'src') && rawName !== 'class') {
      value = rewriteUrl(value);
    }
    out.push(`${attrName}="${value}"`);
  }

  if (!name) return tag;
  return `<${name}${out.length ? ' ' + out.join(' ') : ''}${selfClose ? ' /' : ''}>`;
});

// Drop the redundant outer indentation of the first line only; the rest matches.
body = body.replace(/^\n/, '').replace(/\s+$/, '');

const header = [
  '/* GENERATED by scripts/import-page.mjs from ' + path.basename(fromArg) + ' — review, then own it. */',
  usedCss ? "import { css } from '@/lib/css';" : null,
  '',
  `export function ${componentName}() {`,
  '  return (',
  '    <>',
  '      <main id="main">',
]
  .filter((line) => line !== null)
  .join('\n');

const footer = ['      </main>', '    </>', '  );', '}', ''].join('\n');

const target = path.resolve(process.cwd(), toArg);
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, header + '\n' + body + '\n' + footer);

const lines = body.split('\n').length;
console.log(`import-page: ${fromArg} -> ${toArg} (${componentName}), ${lines} lines, css=${usedCss}`);
void appRoot;
