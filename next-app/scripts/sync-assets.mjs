#!/usr/bin/env node
/**
 * Copies the design system out of the legacy generator into the Next app.
 *
 * The legacy build (`_build/`) stays the single source of truth; this script is
 * the only place the port is allowed to diverge from it. Every divergence is
 * declared and counted below, so drift fails the build instead of shipping.
 *
 * Run: node scripts/sync-assets.mjs   (also runs as part of `npm run build`)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PAGES } from './manifest.mjs';

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(appRoot, '..');
const legacy = path.join(repoRoot, '_build');

const readLegacy = (rel) => fs.readFileSync(path.join(legacy, rel), 'utf8');
const readApp = (rel) => fs.readFileSync(path.join(appRoot, rel), 'utf8');

function writeApp(rel, body) {
  const target = path.join(appRoot, rel);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, body);
}

function assert(condition, message) {
  if (!condition) {
    console.error(`sync-assets: ${message}`);
    process.exit(1);
  }
}

const BANNER = (sources) =>
  `/* GENERATED by scripts/sync-assets.mjs — do not edit.\n` +
  `   Sources: ${sources.join(', ')} (in the repository root).\n` +
  `   Edit those, then re-run \`npm run sync\`. */\n`;

/* ---------------------------------------------------------------- 1. CSS ---
 * Two declared divergences from _build/styles.css:
 *   a) fonts come from next/font, so the family name is generated per build and
 *      the literal families must become `var(--font-*)` (tokens.css, 2 values).
 *   b) the reveal gate moves from `html.js` to `html.reveal-ready`, so content is
 *      only hidden by the same script that is able to unhide it (fail-open).
 */
let tokens = readLegacy('tokens.css');
let styles = readLegacy('styles.css');

for (const [from, to] of [
  ["'Barlow'", 'var(--font-barlow)'],
  ["'Titillium Web'", 'var(--font-titillium)'],
]) {
  assert(tokens.includes(from), `tokens.css no longer contains ${from} — update sync-assets.mjs`);
  tokens = tokens.split(from).join(to);
}

// next/font's variable already expands to `name, "name Fallback"`, so keeping
// the second family in the display stack would nest two fallback chains and
// produce a 12-family list. The tail after the font variables stays byte-equal
// to the legacy tokens.
const DISPLAY_PREFIX = '--font-display:var(--font-titillium),var(--font-barlow),';
assert(tokens.includes(DISPLAY_PREFIX), 'display stack changed in tokens.css — update sync-assets.mjs');
tokens = tokens.replace(DISPLAY_PREFIX, '--font-display:var(--font-titillium),');

const GATE = '.js [data-reveal]';
const gateSites = styles.split(GATE).length - 1;
assert(gateSites === 3, `expected 3 occurrences of "${GATE}" in styles.css, found ${gateSites} — update sync-assets.mjs`);
styles = styles.split(GATE).join('.reveal-ready [data-reveal]');

// The revealed state is an attribute, not a class: React owns every className
// declared in JSX, so a pre-hydration class is a mismatch it may undo — which
// would leave an already-unobserved element at opacity 0 for good.
const IN_SELECTOR = '.reveal-ready [data-reveal].in';
assert(styles.includes(IN_SELECTOR), 'revealed-state selector changed in styles.css — update sync-assets.mjs');
styles = styles.replace(IN_SELECTOR, '.reveal-ready [data-reveal][data-revealed]');
assert(!styles.includes('.reveal-ready [data-reveal].in'), 'revealed-state selector was not fully rewritten');

// The plate cascade and the no-js fallback stay on `.js` on purpose: the runtime
// still sets that class, and the CSS for both is independent of the reveal gate.
assert(styles.includes('.js .layer__cells .cell'), 'plate cascade selector changed — reveal gate relies on .js staying too');

writeApp('src/styles/globals.css', BANNER(['_build/tokens.css', '_build/styles.css']) + tokens + '\n' + styles);

/* ------------------------------------------------------------- 2. Fonts ---
 * fonts.css carries five faces as base64. next/font/local needs real files, so
 * they are decoded once here. The set is asserted, not discovered.
 */
const facesCss = readLegacy('fonts/fonts.css');
const EXPECTED_FACES = [
  ['Barlow', '400'],
  ['Barlow', '500'],
  ['Barlow', '600'],
  ['Titillium Web', '600'],
  ['Titillium Web', '700'],
];

const faces = [...facesCss.matchAll(/@font-face\{([^}]+)\}/g)].map((m) => {
  const body = m[1];
  const family = /font-family:'([^']+)'/.exec(body)?.[1];
  const weight = /font-weight:(\d+)/.exec(body)?.[1];
  const data = /base64,([A-Za-z0-9+/=]+)/.exec(body)?.[1];
  assert(family && weight && data, 'fonts.css @font-face is not in the expected shape');
  return { family, weight, data };
});

assert(faces.length === EXPECTED_FACES.length, `expected ${EXPECTED_FACES.length} faces, found ${faces.length}`);

const fontFiles = [];
for (const [family, weight] of EXPECTED_FACES) {
  const face = faces.find((f) => f.family === family && f.weight === weight);
  assert(face, `fonts.css is missing ${family} ${weight}`);
  const slug = family.toLowerCase().replace(/\s+/g, '-');
  const name = `${slug}-${weight}.woff2`;
  const bytes = Buffer.from(face.data, 'base64');
  assert(bytes.length > 4096, `${name} looks truncated (${bytes.length} bytes)`);
  writeApp(`src/fonts/${name}`, bytes);
  fontFiles.push(name);
}

/* ------------------------------------------------------------ 3. Sprite ---
 * 68 symbols, inlined once per document from the root layout. The generated
 * union is what stops an icon name typo from rendering an empty box.
 */
const sprite = readLegacy('icons.svg');
assert(!sprite.includes('`') && !sprite.includes('${'), 'icons.svg contains a template-literal hazard');
const names = [...sprite.matchAll(/<symbol id="([a-z0-9-]+)"/g)].map((m) => m[1]);
assert(names.length === 68, `expected 68 symbols, found ${names.length}`);
assert(new Set(names).size === names.length, 'duplicate symbol id in icons.svg');

writeApp(
  'src/components/icons.generated.ts',
  BANNER(['_build/icons.svg']) +
    `export const SPRITE = \`${sprite}\`;\n\n` +
    `export const ICON_NAMES = [\n${names.map((n) => `  '${n}',`).join('\n')}\n] as const;\n\n` +
    `export type IconName = (typeof ICON_NAMES)[number];\n`,
);

/* ------------------------------------------------------------ 4. Assets ---
 * Root-relative paths so the same <img> works from any route.
 */
const imgSrc = path.join(repoRoot, 'assets', 'img');
const imgOut = path.join(appRoot, 'public', 'assets', 'img');
fs.mkdirSync(imgOut, { recursive: true });
let copied = 0;
for (const entry of fs.readdirSync(imgSrc, { withFileTypes: true })) {
  if (!entry.isFile()) continue;
  if (entry.name === 'brand-icon-source.png') continue; // 1.3 MB master, not shipped
  fs.copyFileSync(path.join(imgSrc, entry.name), path.join(imgOut, entry.name));
  copied += 1;
}

/* --------------------------------------------------------- 5. Redirects ---
 * `output: 'export'` cannot use next.config redirects, so the legacy flat URLs
 * are described for static hosts. 301 for the old file, 200 rewrite for hosts
 * that do not resolve extensionless paths to `.html`.
 */
const lines = [
  '# GENERATED by scripts/sync-assets.mjs — legacy flat URLs -> clean routes.',
  '# Netlify and Cloudflare Pages both read this file from the publish root.',
  '# /<slug>.html -> 301 /<slug>   then   /<slug> -> 200 /<slug>.html',
];

for (const page of PAGES) {
  if (page.kind === 'not-found') continue;
  const legacyPath = page.slug === '' ? '/index.html' : `/${page.slug}.html`;
  const route = page.slug === '' ? '/' : `/${page.slug}`;
  lines.push(`${legacyPath}  ${route}  301`);
  if (page.slug !== '') {
    // Export emits <slug>.html plus a <slug>/ directory of RSC payloads, so a
    // request to /<slug>/ must resolve to the page, not to that directory.
    lines.push(`${route}  /${page.slug}.html  200`);
    lines.push(`${route}/  /${page.slug}.html  200`);
  }
}

writeApp('public/_redirects', lines.join('\n') + '\n');

console.log(
  [
    `sync-assets: css ${Math.round((tokens.length + styles.length) / 1024)} KB,`,
    `${fontFiles.length} fonts, ${names.length} symbols,`,
    `${copied} images, ${PAGES.length} routes`,
  ].join(' '),
);
